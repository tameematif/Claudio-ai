import { NextRequest, NextResponse } from 'next/server';

interface ChatRequestBody {
  messages: Array<{ role: string; content: string }>;
  model: string;
  temperature?: number;
  maxTokens?: number;
  apiUrl?: string;
  apiKey?: string;
  healthCheck?: boolean;
}

export async function POST(req: NextRequest): Promise<Response> {
  let body: ChatRequestBody;

  try {
    body = await req.json();
  } catch {
    return NextResponse.json(
      { error: 'Invalid JSON payload' },
      { status: 400 }
    );
  }

  const API_URL = (body.apiUrl && body.apiUrl.trim() !== '') 
    ? body.apiUrl.trim().replace(/\/+$/, '') 
    : (process.env.AI_API_URL || 'http://localhost:11434/v1').replace(/\/+$/, '');

  const API_KEY = (body.apiKey !== undefined && body.apiKey !== '') 
    ? body.apiKey 
    : (process.env.AI_API_KEY || '');

  const DEFAULT_MODEL = process.env.AI_MODEL || 'llama3';
  const TIMEOUT = parseInt(process.env.AI_REQUEST_TIMEOUT || '60000', 10);
  const selectedModel = body.model || DEFAULT_MODEL;

  // Mock AI Demo Mode handler
  if (selectedModel === 'mock-ai' || API_URL === 'mock') {
    if (body.healthCheck) {
      return NextResponse.json({ status: 'connected', latency: 5 });
    }

    const lastUserMessage = body.messages[body.messages.length - 1]?.content || 'Hello';
    const mockResponseText = `I am running in **Mock AI (Demo Mode)**. Here is a simulated response to your prompt: "${lastUserMessage}"\n\n` +
      `Here is a sample TypeScript component you can insert into your editor:\n\n` +
      `\`\`\`typescript\n` +
      `// Demo Component generated by Claudio AI\n` +
      `export interface UserProfile {\n` +
      `  id: string;\n` +
      `  name: string;\n` +
      `  role: string;\n` +
      `}\n\n` +
      `export function renderProfile(user: UserProfile): string {\n` +
      `  return \`User \${user.name} (\${user.role}) is active.\`;\n` +
      `}\n` +
      `\`\`\`\n\n` +
      `💡 *Tip: Click **Insert** on the code block above to append it directly into your open editor tab! You can also connect to local Ollama/LM Studio or OpenAI in Settings (⚙️).*`;

    const encoder = new TextEncodingEncoder();
    const stream = new ReadableStream({
      async start(controller) {
        const words = mockResponseText.split(' ');
        for (let i = 0; i < words.length; i++) {
          const chunk = (i === 0 ? '' : ' ') + words[i];
          const payload = {
            choices: [{ delta: { content: chunk } }],
          };
          controller.enqueue(encoder.encode(`data: ${JSON.stringify(payload)}\n\n`));
          await new Promise((resolve) => setTimeout(resolve, 30));
        }
        controller.enqueue(encoder.encode('data: [DONE]\n\n'));
        controller.close();
      },
    });

    return new Response(stream, {
      status: 200,
      headers: {
        'Content-Type': 'text/event-stream',
        'Cache-Control': 'no-cache',
        Connection: 'keep-alive',
      },
    });
  }

  if (!body.messages || !Array.isArray(body.messages) || body.messages.length === 0) {
    return NextResponse.json(
      { error: 'Messages array is required and must not be empty' },
      { status: 400 }
    );
  }

  if (body.healthCheck) {
    try {
      const healthRes = await fetch(`${API_URL}/models`, {
        headers: API_KEY ? { Authorization: `Bearer ${API_KEY}` } : {},
        signal: AbortSignal.timeout(5000),
      });
      if (healthRes.ok) {
        return NextResponse.json({ status: 'connected' });
      }
      return NextResponse.json(
        { error: `AI provider at ${API_URL} returned status ${healthRes.status}` },
        { status: 502 }
      );
    } catch {
      return NextResponse.json(
        { error: `AI provider unreachable at ${API_URL}` },
        { status: 502 }
      );
    }
  }

  const headers: Record<string, string> = {
    'Content-Type': 'application/json',
  };
  if (API_KEY) {
    headers['Authorization'] = `Bearer ${API_KEY}`;
  }

  let upstreamResponse: Response;

  try {
    upstreamResponse = await fetch(`${API_URL}/chat/completions`, {
      method: 'POST',
      headers,
      body: JSON.stringify({
        model: selectedModel,
        messages: body.messages,
        temperature: body.temperature ?? 0.7,
        max_tokens: body.maxTokens ?? 4096,
        stream: true,
      }),
      signal: AbortSignal.timeout(TIMEOUT),
    });
  } catch (error: unknown) {
    const isTimeout = error instanceof Error && error.name === 'TimeoutError';
    const detailMessage = isTimeout
      ? `Request timed out after ${TIMEOUT}ms`
      : `Could not connect to AI provider at ${API_URL}. Ensure your local server (Ollama/LM Studio) is running, or set your API Endpoint & Key in Settings (⚙️), or switch Model to 'Mock AI (Demo Mode)'.`;
    
    return NextResponse.json(
      { 
        error: 'Failed to connect to AI provider',
        detail: detailMessage,
        targetUrl: API_URL
      }, 
      { status: 502 }
    );
  }

  if (!upstreamResponse.ok) {
    const errorText = await upstreamResponse.text().catch(() => 'Unknown error');
    return NextResponse.json(
      {
        error: `AI provider (${API_URL}) returned HTTP ${upstreamResponse.status}`,
        detail: errorText,
      },
      { status: upstreamResponse.status }
    );
  }

  if (!upstreamResponse.body) {
    return NextResponse.json(
      { error: 'No response body from AI provider' },
      { status: 502 }
    );
  }

  const transformStream = new TransformStream({
    transform(chunk, controller) {
      controller.enqueue(chunk);
    },
  });

  upstreamResponse.body.pipeTo(transformStream.writable).catch(() => {
    // Stream closed by client — safe to ignore
  });

  return new Response(transformStream.readable, {
    status: 200,
    headers: {
      'Content-Type': 'text/event-stream',
      'Cache-Control': 'no-cache, no-store, must-revalidate',
      Connection: 'keep-alive',
      'X-Accel-Buffering': 'no',
    },
  });
}

class TextEncodingEncoder {
  private encoder = new TextEncoder();
  encode(input: string): Uint8Array {
    return this.encoder.encode(input);
  }
}
